export const getCityPreviewImage = (destination, previewImage = null) => {
  const destLower = (destination || '').toLowerCase().trim();
  
  const tajMahalImgId = 'photo-1524492412937-b28074a5d7da';
  const oldTajMahalImgId = 'photo-1561361513-2d000a50f0db';
  
  // Custom pre-screened city images (highly active, verified Unsplash URLs)
  if (destLower.includes('chandigarh')) {
    return "https://images.unsplash.com/photo-1476514525535-07fb3b4ae5f1?auto=format&fit=crop&w=800&q=80"; // Serene Sukhna Lake boat representative
  }
  if (destLower.includes('varanasi')) {
    return "https://images.unsplash.com/photo-1618083707368-b3823daa2726?auto=format&fit=crop&w=800&q=80"; // Ganga Ghat Varanasi
  }
  if (destLower.includes('agra')) {
    return "https://images.unsplash.com/photo-1564507592333-c60657eea523?auto=format&fit=crop&w=800&q=80"; // Taj Mahal Agra
  }
  if (destLower.includes('delhi') || destLower.includes('del') || destLower.includes('noida') || destLower.includes('gurgaon')) {
    return "https://images.unsplash.com/photo-1587474260584-136574528ed5?auto=format&fit=crop&w=800&q=80"; // Red Fort Delhi (Verified Working!)
  }
  if (destLower.includes('jaipur')) {
    return "https://images.unsplash.com/photo-1603262110263-fb0112e7cc33?auto=format&fit=crop&w=800&q=80"; // Hawa Mahal Jaipur (Verified Active!)
  }
  if (destLower.includes('mumbai') || destLower.includes('bom')) {
    return "https://images.unsplash.com/photo-1529253355930-ddbe423a2ac7?auto=format&fit=crop&w=800&q=80"; // Gateway of India & Taj Palace Hotel Mumbai (Verified Active!)
  }
  if (destLower.includes('patna')) {
    return "https://images.unsplash.com/photo-1590050752117-238cb0fb12b1?auto=format&fit=crop&w=800&q=80"; // Ganges River boat ride representative (Verified Active!)
  }
  if (destLower.includes('amritsar')) {
    return "https://images.unsplash.com/photo-1514222134-b57cbb8ce073?auto=format&fit=crop&w=800&q=80"; // Golden Temple Amritsar
  }
  if (destLower.includes('bangalore') || destLower.includes('bengaluru')) {
    return "https://images.unsplash.com/photo-1596176530529-78163a4f7af2?auto=format&fit=crop&w=800&q=80"; // Bangalore Palace (Verified Active!)
  }
  if (destLower.includes('kolkata') || destLower.includes('calcutta')) {
    return "https://images.unsplash.com/photo-1558431382-27e303142255?auto=format&fit=crop&w=800&q=80"; // Victoria Memorial Kolkata (Verified Active!)
  }
  if (destLower.includes('goa')) {
    return "https://images.unsplash.com/photo-1512343879784-a960bf40e7f2?auto=format&fit=crop&w=800&q=80"; // Goa Sunset Beach (Verified Active!)
  }
  if (destLower.includes('shimla')) {
    return "https://images.unsplash.com/photo-1562979314-bee7453e911c?auto=format&fit=crop&w=800&q=80"; // Shimla Ridge (Verified Active!)
  }
  if (destLower.includes('manali')) {
    return "https://images.unsplash.com/photo-1605649487212-47bdab064df7?auto=format&fit=crop&w=800&q=80"; // Solang Valley Manali (Verified Active!)
  }
  if (destLower.includes('pune')) {
    return "https://images.unsplash.com/photo-1601042879364-f3947d3f9c16?auto=format&fit=crop&w=800&q=80"; // Shaniwar Wada Pune
  }
  
  // If we have a custom non-fallback preview image already, return it
  if (previewImage && !previewImage.includes(tajMahalImgId) && !previewImage.includes(oldTajMahalImgId)) {
    return previewImage;
  }
  
  // Absolute neutral travel fallback instead of the specific Taj Mahal image (using bulletproof Unsplash URL)
  return "https://images.unsplash.com/photo-1506461883276-594a12b11cf3?auto=format&fit=crop&w=800&q=80";
};
